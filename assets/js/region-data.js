/** 위도/경도와 가장 가까운 시도를 근사적으로 찾는다 (데모용 단순 거리 계산). */
function findNearestSido(lat, lng) {
  let best = null;
  let bestDist = Infinity;
  for (const c of SIDO_CENTERS) {
    const d = Math.pow(c.lat - lat, 2) + Math.pow(c.lng - lng, 2);
    if (d < bestDist) {
      bestDist = d;
      best = c;
    }
  }
  return best ? best.sido : "서울특별시";
}

